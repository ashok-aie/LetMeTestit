"""
Playwright Test Script Exporter
Generates standalone, runnable Playwright Python test files from TestSuite models
and stores them in app/browser/test_scripts/ for persistent version control and CI/CD execution.
"""
from pathlib import Path
from typing import Optional
from app.models.test_suite import TestSuite, ActionType, LocatorStrategy


TEST_SCRIPTS_DIR = Path("app/browser/test_scripts").resolve()
ARTIFACTS_SCRIPTS_DIR = Path("artifacts/scripts").resolve()


def export_suite_to_playwright_script(
    suite: TestSuite,
    target_url: Optional[str] = None,
    output_dir: Optional[Path] = None,
) -> Path:
    """
    Exports a TestSuite into an executable, standalone Playwright Python test script.
    
    Args:
        suite: Validated TestSuite model.
        target_url: Base application URL.
        output_dir: Target directory (defaults to app/browser/test_scripts/).
        
    Returns:
        Path to the generated Python test script file.
    """
    dest_dir = output_dir or TEST_SCRIPTS_DIR
    dest_dir.mkdir(parents=True, exist_ok=True)
    ARTIFACTS_SCRIPTS_DIR.mkdir(parents=True, exist_ok=True)
    
    clean_id = suite.suite_id.replace("-", "_").lower()
    script_path = dest_dir / f"test_{clean_id}.py"
    artifact_script_path = ARTIFACTS_SCRIPTS_DIR / f"test_{clean_id}.py"

    code_lines = [
        '"""',
        f'Automated Playwright Test Suite: {suite.suite_id}',
        f'Requirement Key: {suite.requirement_key}',
        f'Generated by: Let me TEST it....! Agentic Quality Engineering Platform',
        '"""',
        'import pytest',
        'from playwright.sync_api import Page, expect',
        '',
    ]

    for tc in suite.test_cases:
        tc_fn_name = f"test_{tc.id.replace('-', '_').lower()}_{tc.category.value}"
        code_lines.extend([
            f'def {tc_fn_name}(page: Page):',
            f'    """',
            f'    [Category: {tc.category.value.upper()}] {tc.title}',
            f'    Objective: {tc.objective}',
            f'    """',
        ])

        for step in tc.steps:
            code_lines.append(f'    # Step {step.step_number}: {step.action.value}')
            selector = step.selector_value or ""
            strategy = step.locator_strategy.value if step.locator_strategy else "test_id"

            if step.action == ActionType.NAVIGATE:
                dest = step.input_value or target_url or "http://127.0.0.1:8000"
                code_lines.append(f'    page.goto("{dest}")')
                code_lines.append(f'    page.wait_for_load_state("networkidle")')

            elif step.action == ActionType.FILL:
                if strategy == "test_id":
                    locator_expr = f'page.get_by_test_id("{selector}")'
                elif strategy == "role":
                    if step.role_name and selector and step.role_name != selector:
                        locator_expr = f'page.get_by_role("{step.role_name}", name="{selector}")'
                    else:
                        locator_expr = f'page.get_by_role("{step.role_name or selector}")'
                elif strategy == "text":
                    locator_expr = f'page.get_by_text("{selector}")'
                else:
                    locator_expr = f'page.locator("{selector}")'
                val = step.input_value or ""
                code_lines.append(f'    {locator_expr}.fill("{val}")')

            elif step.action == ActionType.CLICK:
                if strategy == "test_id":
                    locator_expr = f'page.get_by_test_id("{selector}")'
                elif strategy == "role":
                    if step.role_name and selector and step.role_name != selector:
                        locator_expr = f'page.get_by_role("{step.role_name}", name="{selector}")'
                    else:
                        locator_expr = f'page.get_by_role("{step.role_name or selector}")'
                elif strategy == "text":
                    locator_expr = f'page.get_by_text("{selector}")'
                else:
                    locator_expr = f'page.locator("{selector}")'
                code_lines.append(f'    {locator_expr}.click()')

            elif step.action == ActionType.SELECT_OPTION:
                if strategy == "test_id":
                    locator_expr = f'page.get_by_test_id("{selector}")'
                else:
                    locator_expr = f'page.locator("{selector}")'
                val = step.input_value or ""
                code_lines.append(f'    {locator_expr}.select_option("{val}")')

            elif step.action == ActionType.ASSERT_TEXT:
                expected = step.expected_value or ""
                if selector:
                    if strategy == "test_id":
                        locator_expr = f'page.get_by_test_id("{selector}")'
                    else:
                        locator_expr = f'page.locator("{selector}")'
                    code_lines.append(f'    expect({locator_expr}).to_contain_text("{expected}")')
                else:
                    code_lines.append(f'    expect(page.locator("body")).to_contain_text("{expected}")')

            elif step.action == ActionType.WAIT_FOR:
                if strategy == "test_id":
                    locator_expr = f'page.get_by_test_id("{selector}")'
                else:
                    locator_expr = f'page.locator("{selector}")'
                code_lines.append(f'    {locator_expr}.wait_for(state="visible", timeout=10000)')

            code_lines.append('')
        code_lines.append('')

    content = "\n".join(code_lines)
    script_path.write_text(content, encoding="utf-8")
    try:
        artifact_script_path.write_text(content, encoding="utf-8")
    except Exception:
        pass
    return script_path

